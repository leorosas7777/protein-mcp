def test_a_readme_that_is_not_the_known_shape_is_refused():
    """Control that MUST fail: without cntmax there is no number of chunks to read, and inventing
    one would be a simulation length nobody chose."""
    tmp = Path(tempfile.mkdtemp())
    readme = tmp / "README"
    for text, expected in ((REAL_README.replace("set cntmax = 10", ""), "cntmax"),
                           (REAL_README.replace("set prod_step   = step5", ""), "prod_step"),
                           ("", "no namd/README")):
        readme.write_text(text, encoding="ascii")
        try:
            md_run.readme_scheme(readme if text else tmp / "absent")
        except md_run.MdRunError as exc:
            assert expected in str(exc), (expected, str(exc))
        else:
            raise AssertionError(f"accepted a README without {expected}")


def test_input_values_carry_their_line():
    tmp = Path(tempfile.mkdtemp())
    namd = tmp / "namd"
    namd.mkdir()
    (namd / "step5_production.inp").write_text(REAL_PRODUCTION, encoding="ascii")
    (namd / "step4_equilibration.inp").write_text(REAL_EQUILIBRATION, encoding="ascii")
    values = md_run.input_values(namd, {"prod_prefix": "step5_production",
                                        "equi_prefix": "step4_equilibration"})
    # the length comes from `run`, the line that executes the steps, not from `numsteps`
    assert values["steps_per_chunk_from"] == "run", values["steps_per_chunk_from"]
    assert values["run_line"] == {"line": 14, "value": "500000",
                                  "text": "run                     500000;             # 1ns"}, values
    assert values["numsteps_line"]["line"] == 13
    assert values["nanoseconds_per_chunk"] == 1.0, values            # 500000 x 2 fs
    assert values["length_warning"] is None
    assert values["equilibration_run"]["value"] == "125000"
    assert values["equilibration_minimize"]["value"] == "10000"
    assert values["equilibration_outputname"]["value"] == "step4_equilibration"

    # if the two disagree, the tool reports `run` and says so instead of picking silently
    (namd / "step5_production.inp").write_text(
        REAL_PRODUCTION.replace("numsteps                500000;", "numsteps                999999;"),
        encoding="ascii")
    values = md_run.input_values(namd, {"prod_prefix": "step5_production",
                                        "equi_prefix": "step4_equilibration"})
    assert values["nanoseconds_per_chunk"] == 1.0, values
    assert "NAMD runs the steps of `run`" in values["length_warning"], values["length_warning"]


