# ----------------------------------------------------------------- set-up

def archive_with_namd_scheme(tmp: Path, delivered: Path, to_model, *, readme=REAL_README,
                             name="job.tgz", **kw) -> Path:
    """make_archive of test_md_package, plus namd/README and the two NAMD inputs, re-tarred."""
    make_archive(tmp, delivered, to_model=to_model, **kw)      # leaves tmp/build/<JOB> on disk
    root = tmp / "build" / JOB
    (root / "namd" / "README").write_text(readme, encoding="ascii")
    (root / "namd" / "step5_production.inp").write_text(REAL_PRODUCTION, encoding="ascii")
    (root / "namd" / "step4_equilibration.inp").write_text(REAL_EQUILIBRATION, encoding="ascii")
    (root / "namd" / "toppar").mkdir(exist_ok=True)
    (root / "namd" / "toppar" / "par_all36m_prot.prm").write_text("* parameters\n", encoding="ascii")
    archive = tmp / name
    with tarfile.open(archive, "w:gz") as tar:
        tar.add(root, arcname=JOB)
    return archive


def built():
    """A dossier with a package, and an archive that passes the step-4 checks."""
    prep, delivered = test_build_writes_what_charmm_gui_needs()
    package = json.loads((delivered.parent / "package.json").read_text(encoding="utf-8"))
    tmp = Path(tempfile.mkdtemp())
    archive = archive_with_namd_scheme(tmp, delivered, package["to_model"])
    return prep, delivered, package, tmp, archive


