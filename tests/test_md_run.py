def test_the_real_paste_of_a_cluster():
    """Everything a real `sinfo` does that a tidy fixture does not.

    Before this paste the parser dropped six of nineteen rows over a `+` suffix, missed the only
    NAMD module on the cluster because its name is hierarchical, and treated the six rows of
    `gpu` as six partitions — so it proposed the first one printed, an rtx_2080 with 16 cores,
    while the same partition also has a100 nodes.
    """
    parsed = md_run.parse_site_report(REAL_REPORT)
    assert len(parsed["partitions"]) == 19, len(parsed["partitions"])
    grouped = {p["name"]: p for p in md_run.group_partitions(parsed["partitions"])}
    assert len(grouped) == 10, sorted(grouped)
    assert len(grouped["gpu"]["variants"]) == 6
    assert grouped["gpu"]["gpu_types"] == ["V100", "a100", "rtx_2080", "rtx_3090", "v100"]
    assert grouped["compute"]["is_default"] and not grouped["compute"]["has_gpu"]
    # `16+` means "at least", and is kept as that rather than dropped or passed off as exact
    least = next(v for v in grouped["compute"]["variants"])
    assert (least["cpus_per_node"], least["cpus_is_minimum"]) == (16, True), least
    assert parsed["namd_modules"] == ["apps/namd/3.0.3"], parsed["namd_modules"]
    assert parsed["namd_binaries"] == []
    assert parsed["max_array_size"] == 10000
    assert parsed["unparsed"] == ["PARTITION|TIMELIMIT|GRES|NODES|CPUS|MEMORY"], parsed["unparsed"]

    # the proposal is the general GPU partition, not the group queue with a longer limit
    site = md_run.resolve_site(parsed, 1)
    assert site["fields"]["partition"]["value"] == "gpu", site["fields"]["partition"]
    assert "the most nodes (18)" in site["fields"]["partition"]["source"]
    assert "mwvdk (15-00:00:00, 13 nodes" in site["fields"]["partition"]["source"]
    # with six kinds of node and no model named, NOTHING is sized and the answer says why
    assert site["fields"]["cpus_per_task"]["value"] is None
    assert site["fields"]["mem"]["value"] is None
    assert "none was settled on" in site["fields"]["gpus"]["source"]
    assert any("whichever node the scheduler gives it" in n for n in site["notes"])
    # three accounts, so the tool must not pick one
    assert site["fields"]["account"]["value"] == "CONFIRM_ACCOUNT"
    # the module is there but no binary was on the PATH: the reason says what to do
    assert site["fields"]["namd_module"]["value"] == "apps/namd/3.0.3"
    assert "module that provides it was not loaded" in site["fields"]["namd_binary"]["source"]

    # giving a binary path must NOT drop the module: a binary a module installed needs it for
    # its CUDA libraries, and dropping it silently is how a job dies after queueing
    site = md_run.resolve_site(parsed, 1, partition="gpu",
                               namd_binary="/software/local/apps/NAMD_x86_64-multicore-CUDA/namd3")
    assert site["fields"]["namd_module"]["value"] == "apps/namd/3.0.3", site["fields"]["namd_module"]
    assert "LD_LIBRARY_PATH" in site["fields"]["namd_module"]["source"]
    # the build name is read as evidence for the launch flags
    assert "named `multicore-CUDA`" in site["fields"]["namd_opts"]["source"]
    # and only an explicit "none" leaves it out
    site = md_run.resolve_site(parsed, 1, partition="gpu", namd_module="none",
                               namd_binary="/opt/namd3")
    assert site["fields"]["namd_module"] == {"value": None, "mark": "CHOSEN",
                                             "source": "you said no module is to be loaded"}

    # sinfo says `a100`, the site's GresTypes says `a100-sxm4-40gb`: the tool says so itself
    site = md_run.resolve_site(parsed, 1, partition="gpu", gpu_type="a100")
    assert "does not list that exact name" in site["fields"]["gpus"]["source"]
    assert "a100-sxm4-40gb" in site["fields"]["gpus"]["source"]

    # naming the model sizes the request against THAT node and pins it in the GRES
    site = md_run.resolve_site(parsed, 1, partition="gpu", gpu_type="a100",
                               account="acct000001", namd_binary="/apps/namd/3.0.3/bin/namd3")
    assert site["fields"]["cpus_per_task"]["value"] == 10      # 128 cores / 12 a100 per node
    assert site["fields"]["mem"]["value"] == "41G"             # 515046 MB / 12
    assert site["fields"]["gpus"]["gres"] == "gpu:a100:1", site["fields"]["gpus"]
    assert site["to_confirm"] == {}, site["to_confirm"]
    script = md_run.slurm_text("x", [md_run.system_entry(
        "a/system/namd", "a", {"equi_prefix": "e", "prod_prefix": "p", "prod_step": "s",
                               "chunks": 1},
        {"equilibration_outputname": None, "nanoseconds_per_chunk": 1.0,
         "production_input": "p.inp", "run_line": {"line": 1}, "numsteps_line": {"line": 2}})],
        site)
    assert "#SBATCH --gres=gpu:a100:1" in script, script[:900]
    # a model the cluster never reported is refused
    try:
        md_run.resolve_site(parsed, 1, partition="gpu", gpu_type="h100")
    except md_run.MdRunError as exc:
        assert "does not report a GPU called" in str(exc) or "No node type" in str(exc), str(exc)
    else:
        raise AssertionError("accepted a GPU model nobody reported")


